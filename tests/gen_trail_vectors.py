#!/usr/bin/env python3
"""Write tests/trail_vectors_test.cho from lex-trail's spec/vectors.json.

    python3 tests/gen_trail_vectors.py /path/to/lex-trail/spec/vectors.json > tests/trail_vectors_test.cho

Nothing is computed here: every id and digest is copied from the vectors file, which lex-trail generates from its own
implementation and checks with its own spec/verify_vectors.py. The test file is generated so that it cannot drift by hand.
"""
import json
import sys


def lit(s):
    out = ""
    for ch in s:
        if ch == '"':
            out += '\\"'
        elif ch == "\\":
            out += "\\\\"
        elif ch == "\0":
            out += "\\0"
        elif ch == "\n":
            out += "\\n"
        else:
            out += ch
    return '"' + out + '"'


def main():
    d = json.load(open(sys.argv[1]))
    o = []
    o.append("edition 5;\n\nimport std.test;\nimport trail;\n")
    o.append("// GENERATED by tests/gen_trail_vectors.py from lex-trail's spec/vectors.json. Do not edit by hand.\n"
             "//\n// Every event id and anchor digest below is lex-trail's, not computed by this engine.\n")
    o.append("""fn expect_hex[&o, &w](out: &o [byte], want: &w [byte]) -> [] int {
    test.assert_eq(len(want), 64);
    var i = 0;
    while i < 64 {
        test.assert_eq(int_of(out[i]), int_of(want[i]));
        i = i + 1;
    }
    return 0;
}

fn expect_id[&k, &p, &l, &w](kind: &k [byte], parent: &p [byte], payload: &l [byte], ts_ms: int, want: &w [byte]) -> [] int {
    region a {
        let out = alloc_slice[a](64, byte_of(0));
        test.assert_eq(trail.check_event(kind, parent, payload, ts_ms), 0);
        trail.event_id(kind, parent, payload, ts_ms, out);
        expect_hex(out, want);
    }
    return 0;
}

fn expect_anchor[&d, &w](ids: &d [byte], count: int, want: &w [byte]) -> [] int {
    region a {
        let out = alloc_slice[a](64, byte_of(0));
        test.assert_eq(trail.anchor_digest(ids, count, out), 0);
        expect_hex(out, want);
    }
    return 0;
}
""")
    for i, e in enumerate(d["events"]):
        o.append("fn test_event_%d() -> [] int {\n    expect_id(%s, %s, %s, %d, \"%s\");\n    return 0;\n}\n"
                 % (i, lit(e["kind"]), lit(e["parent"]), lit(e["payload_json"]), e["ts_ms"], e["id"]))
    for i, a in enumerate(d["anchors"]):
        ids = "".join(x + "\0" for x in a["ids"])
        o.append("fn test_anchor_%d() -> [] int {\n    expect_anchor(%s, %d, \"%s\");\n    return 0;\n}\n"
                 % (i, lit(ids), len(a["ids"]), a["digest"]))
    print("\n".join(o))


main()
